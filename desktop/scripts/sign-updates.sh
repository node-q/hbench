#!/bin/bash
# Signs a release's in-app update payloads with the updater key and writes latest.json, the manifest the app
# polls (see src-tauri/tauri.conf.json → plugins.updater; the app reads it from the latest release).
#
#   sign-updates.sh <dist dir> <tag> <owner/repo>
#
# Payloads it looks for in <dist dir>; a platform whose file is missing is left out of the manifest:
#   Actuaria-<tag>-{aarch64,x86_64}-apple-darwin.app.tar.gz        macOS (from package-macos.sh)
#   Actuaria-<tag>-x86_64-pc-windows-msvc-setup.exe                Windows (the NSIS installer itself)
#   Actuaria-<tag>-{x86_64,aarch64}-unknown-linux-gnu.{deb,rpm}    Linux packages
# It writes <file>.sig next to each, and latest.json. The key comes from the environment:
#   TAURI_SIGNING_PRIVATE_KEY            the key generated by `tauri signer generate`
#   TAURI_SIGNING_PRIVATE_KEY_PASSWORD   its password
# Each signature is bound to the release's version (the app sets requireSignedVersion), so a manifest can't
# pass an older package off as a newer one.
set -euo pipefail
dist="${1:?usage: sign-updates.sh <dist dir> <tag> <owner/repo>}"
tag="${2:?usage: sign-updates.sh <dist dir> <tag> <owner/repo>}"
repo="${3:?usage: sign-updates.sh <dist dir> <tag> <owner/repo>}"
version="${tag#v}"
here="$(cd "$(dirname "$0")/.." && pwd)"
: "${TAURI_SIGNING_PRIVATE_KEY:?TAURI_SIGNING_PRIVATE_KEY is not set}"

platforms='{}'
add() { # <updater target> <file name>
  local file="$dist/$2"
  [ -f "$file" ] || { echo "skipping $1: no $2" >&2; return; }
  (cd "$here" && npx --no-install tauri signer sign --app-version "$version" "$file" >/dev/null)
  platforms=$(jq --arg t "$1" --arg url "https://github.com/$repo/releases/download/$tag/$2" --rawfile sig "$file.sig" \
    '.[$t] = {url: $url, signature: ($sig | rtrimstr("\n"))}' <<<"$platforms")
  echo "signed $1: $2"
}

for arch in aarch64 x86_64; do
  # `{os}-{arch}` serves the app whatever bundle type it reports; macOS has only the one.
  add "darwin-$arch" "Actuaria-$tag-$arch-apple-darwin.app.tar.gz"
  # Linux is looked up by package type: a .deb install gets the .deb, an .rpm install the .rpm.
  add "linux-$arch-deb" "Actuaria-$tag-$arch-unknown-linux-gnu.deb"
  add "linux-$arch-rpm" "Actuaria-$tag-$arch-unknown-linux-gnu.rpm"
done
add "windows-x86_64" "Actuaria-$tag-x86_64-pc-windows-msvc-setup.exe"

[ "$platforms" != '{}' ] || { echo "error: no update payloads in $dist" >&2; exit 1; }
jq -n --arg v "$version" --arg notes "https://github.com/$repo/releases/tag/$tag" --arg date "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
  --argjson p "$platforms" '{version: $v, notes: $notes, pub_date: $date, platforms: $p}' > "$dist/latest.json"
echo "wrote $dist/latest.json for: $(jq -r 'keys | join(", ")' <<<"$platforms")"
